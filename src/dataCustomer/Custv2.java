        String cari = jTextField_search.getText();
        ArrayList<String> filter = new ArrayList<>();
        StringBuilder sql = new StringBuilder("SELECT * FROM customer");
        if (!cari.isEmpty()) {
            filter.add("no_ktp  LIKE '%" + cari + "%' or nama_lengkap  LIKE '%" + cari + "%' or kd_customer  LIKE '%" + cari + "%'");
        }
        if (!filter.isEmpty()) {
            sql.append(" WHERE ").append(String.join(" AND ", filter));
        }
        if (filterType.equals("Terlama")) {
            sql.append(" ORDER BY kd_customer ASC;");
        } else if (filterType.equals("Terbaru")) {
            sql.append(" ORDER BY kd_customer DESC;");
        }
        String newSql = sql.toString();
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_customer"),
                    res.getString("kd_customer"),
                    res.getString("no_ktp"),
                    res.getString("nama_lengkap"),
                    res.getString("alamat"),
                    res.getString("no_telp"),});
                jTableCust.setModel(tbl);
                jTableCust.getColumnModel().getColumn(6).setCellRenderer(new tabelActionRender());
                jTableCust.getColumnModel().getColumn(6).setCellEditor(new TableActionEditor(event));
            }
        } catch (Exception e) {
            pop_upnoData nodata = new pop_upnoData();
            nodata.setVisible(true);
        }
