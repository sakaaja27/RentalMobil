    public void datatable(String d1,String d2) {
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Nama User");
        tbl.addColumn("Kode User");
        tbl.addColumn("Tgl Log");
        tbl.addColumn("Kegiatan");
        jTableLog.setModel(tbl);
        
        PreparedStatement st;
        ResultSet rs;
        try {
            if (d1.equals("") || d2.equals("")) {
                st = DB.getConnection().prepareStatement("SELECT user.nama_lengkap,log.* FROM `log` INNER JOIN user ON log.kd_user = user.kd_user; ");
            }
            else {
                st = DB.getConnection().prepareStatement("SELECT user.nama_lengkap,log.* FROM `log` INNER JOIN user ON log.kd_user = user.kd_user where log.tgl_log between ? and ? ");
                st.setString(1, d1);
                st.setString(2, d2);
            }
            
            rs = st.executeQuery();
            DefaultTableModel model = (DefaultTableModel) jTableLog.getModel();
            
            Object[] row;
            
            while(rs.next()){
                tbl.addRow(new Object[]{
                    rs.getString("nama_lengkap"),
                    rs.getString("kd_user"),
                    rs.getString("tgl_log"),
                    rs.getString("kegiatan")
                });
                jTableLog.setModel(tbl);
            }
        }
        catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data tidak ada");
        }
        
    }
