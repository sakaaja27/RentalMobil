    void getData(String id_pemilik) {
        try {

            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery("SELECT * FROM pemilik_mobil where kd_pemilik ='"+id_pemilik+"'");

            while (res.next()) {
                namaPemilik.setText(res.getString("nama_pemilik"));
                noKtp.setText(res.getString("no_ktp"));
                noTelp.setText(res.getString("no_telp"));
                alamat.setText(res.getString("alamat"));
                //                   status.setText(res.getString("nopol"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, e);

        }
    }
