    private void saveMobilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveMobilActionPerformed
        // TODO add your handling code here:

        String nama_pemilik = namaPemilik.getText();
        String noktp = noKtp.getText();
        String no_tlp = noTelp.getText();
        String Alamat = alamat.getText();
        String num = kodePemilik.getText();

        //        String status = statusMobil.getText();
        try {

            Statement statement = (Statement) DB.getConnection().createStatement();
            String sql;
            if (id != null) {   
                sql = "UPDATE `pemilik_mobil` SET `nama_pemilik`='"+nama_pemilik+"',`alamat`='"+Alamat+"',`no_telp`='"+no_tlp+"',`no_ktp`='"+noktp+"' WHERE kd_pemilik = '"+kodePemilik.getText()+"'";
                JOptionPane.showMessageDialog(null,"Data berhasil di Ubah");
            } else {
                ResultSet res = statement.executeQuery("SELECT genPemilikID() AS pemilikID");
                String kdPemilik = ""; 
                if(res.next()){
                    kdPemilik = res.getString("pemilikID");
                }
                sql = "insert into pemilik_mobil VALUES('" + kdPemilik + "','" + nama_pemilik + "', '" + Alamat + "', '" + no_tlp + "','" + noktp + "');";
                JOptionPane.showMessageDialog(null,"Data berhasil di simpan");
            }
            statement.executeUpdate(sql);
            statement.close();
            System.out.println(sql);
            DataPemilik.datatable();
            
            this.dispose();
        } catch (Exception e) {
            System.out.println(e);
            JOptionPane.showMessageDialog(null, "data gagal di SIMPAN");
        }
    }//GEN-LAST:event_saveMobilActionPerformed

    private void jButton_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_hapusActionPerformed
        // TODO add your handling code here:
        try {
            if (id != null) {
                Statement statement = (Statement) DB.getConnection().createStatement();
                String sql;
                if (JOptionPane.showConfirmDialog(null, "Yakin ingin menghapus ?", "Konfirmasi", JOptionPane.OK_CANCEL_OPTION) == JOptionPane.OK_OPTION) {
                    sql = "DELETE FROM pemilik_mobil where kd_pemilik = '" + kodePemilik.getText() + "'";
                    java.sql.Connection conn = (Connection) DB.getConnection();
                    java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                    pst.execute();
                    JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
                    DataPemilik.datatable();
                    this.dispose();

                }

            } else {
                namaPemilik.setText(null);
                noKtp.setText(null);
                noTelp.setText(null);
                alamat.setText(null);
                JOptionPane.showMessageDialog(this, "Data berhasil dikosongkan");

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_jButton_hapusActionPerformed

