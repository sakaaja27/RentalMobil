    public void datatable() {
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kode Sopir");
//        tbl.getColumnName("Kode Mobil" ).
        tbl.addColumn("No.KTP");
        tbl.addColumn("Nama Sopir");

        tbl.addColumn("Alamat");
        tbl.addColumn("Alamat");
        tbl.addColumn("Status");
//        tbl.addColumn("Gambar");
        jTableSopir.setModel(tbl);
        jTableSopir.getColumnModel().getColumn(0).setMinWidth(0);
        jTableSopir.getColumnModel().getColumn(0).setMaxWidth(0);

        String cari = jTextField_search.getText();

        String filterStatus = jComboBox_filterStatus.getSelectedItem().toString();
        ArrayList<String> filter = new ArrayList<>();
        StringBuilder sql = new StringBuilder("SELECT * FROM supir");
        if (!cari.isEmpty()) {
            filter.add("nama_supir LIKE '%" + cari + "%' OR no_ktp LIKE '%" + cari + "%'");
        }
        

        if (!filterStatus.isEmpty() && filterStatus != "Semua") {
            filter.add("status = '"+filterStatus+"'");
        }
        
        if (!filter.isEmpty()) {
            sql.append(" WHERE ").append(String.join(" AND ", filter));
        }
        String newSql = sql.toString();
        System.out.println(newSql);
        try {

            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_supir"),
                    res.getString("no_ktp"),
                    res.getString("nama_supir"),
                    res.getString("no_telp"),
                    res.getString("alamat"),
                    //                     res.getString("gambar"),
                    res.getString("status")
                });
                jTableSopir.setModel(tbl);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data tidak ada");
        }
    }
