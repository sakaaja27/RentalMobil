    private void jButton_submitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_submitActionPerformed
        // TODO add your handling code here:
        String kd_pembatalan = kodePembatalan1.getText();
        String ganti_rugi = gantiRugi.getText();
        String tgl_pembatalan = sdf.format(new Date());

        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            String sql, sql1, sql2, sql3;
            sql = "insert into pembatalan VALUES('" + kd_pembatalan + "','" + kd_user + "','" + kd_mobil + "','" + tgl_pembatalan + "','" + ganti_rugi + "');";
            statement.executeUpdate(sql);
            if (kd_supir != null) {
                sql3 = "UPDATE supir set status='bersedia' where kd_supir= '" + kd_supir + "'";
                statement.executeUpdate(sql3);
            }
            sql2 = "UPDATE mobil set status='tersedia' where kd_mobil= '" + kd_mobil + "'";
            statement.executeUpdate(sql2);
            sql1 = "DELETE FROM detail_sewa WHERE kd_detail_sewa='" + kd_detail_sewa + "'";
            statement.executeUpdate(sql1);
            JOptionPane.showMessageDialog(null, "Penyimpanan Data Berhasil");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_jButton_submitActionPerformed

