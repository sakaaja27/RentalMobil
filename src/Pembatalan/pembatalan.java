    void genPembatalanID(String kd_detail_sewa) {
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res;
            res = statement.executeQuery("SELECT genPembatalanID() AS batalID");
            if (res.next()) {
                kodePembatalan1.setText(res.getString("batalID"));
            }

//            if (res.next()) {
//                kodePembatalan1.setText(); = res.getString("batalID");
//            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

    void getPembatalan() {
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery("SELECT v_pra_pelanggaran.kd_user, v_pra_pelanggaran.kd_supir, v_pra_pelanggaran.kd_mobil, v_pra_pelanggaran.nama_user, v_pra_pelanggaran.nama_mobil from v_pra_pelanggaran WHERE kd_detail_sewa='" + kd_detail_sewa + "'");
            if (res.next()) {
                kodeMobil.setText(res.getString("nama_mobil"));
                kodeUser.setText(res.getString("nama_user"));
                kd_user = res.getString("kd_user");
                kd_mobil = res.getString("kd_mobil");
                kd_supir = res.getString("kd_supir");
            }
        } catch (Exception e) {
//            JOptionPane.showMessageDialog(null, e.getMessage());
            System.out.println(e);
        }
    }


