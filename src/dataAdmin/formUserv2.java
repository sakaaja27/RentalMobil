    private void saveMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_saveMouseClicked
        // TODO add your handling code here:
        String nama_lengkap = namaLengkap.getText();
        String User = username.getText();
        String Pass = jPasswordField.getText();
        String alamat = Alamat.getText();
        String hp = noHp.getText();
        String role = null;
        if (jowner.isSelected()) {
            role = "Owner";
        }
        if (jadmin.isSelected()) {
            role = "Admin";
        }
        if (role != null && role.length() > 10) {
            role = role.substring(0, 10);
        }

        // Validation for required data
        if (nama_lengkap.isEmpty() || User.isEmpty() || Pass.isEmpty() || alamat.isEmpty() || hp.isEmpty() || role == null) {
            pop_upRequired required = new pop_upRequired();
            required.setVisible(true);
            return;
        }
//        byte[] RF = RFID.getBytes();
        String num = kodeUser.getText();
        
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            String sql;
            if (id != null) {
                sql = "UPDATE `user` SET `nama_lengkap`='" + nama_lengkap + "',`username`='" + User + "',`password`='" + Pass + "',`role`='" + role + "',`alamat`='" + alamat + "',`hp`='" + hp + "',`rfid`='" + RFID + "' WHERE kd_user='" + kodeUser.getText() + "'";
                statement.executeUpdate(sql);
                pop_upDataberhasil dataubah = new pop_upDataberhasil();
                dataubah.setVisible(true);
                PreparedStatement ps;
                ps = DB.getConnection().prepareStatement("SELECT * FROM log ORDER BY tgl_log DESC");
                ResultSet result = ps.executeQuery();
                while (result.next()) {
                    String activity = "Melakukan Perubahan data User";
                    ps = DB.getConnection().prepareStatement("CALL createLog('" + result.getString("kd_user") + "','" + activity + "');");
                    ps.executeUpdate();
                    break;
                }
            } else {
                ResultSet res = statement.executeQuery("SELECT genUserID() AS userID");
                String kdUser = "";
                if (res.next()) {
                    kdUser = res.getString("userID");
                }
                sql = "INSERT INTO user VALUES ('" + kdUser + "','" + nama_lengkap + "','" + RFID + "','" + User + "','" + Pass + "','" + role + "','" + alamat + "','" + hp + "');";
                PreparedStatement ps;
                ps = DB.getConnection().prepareStatement("SELECT * FROM log ORDER BY tgl_log DESC");
                ResultSet result = ps.executeQuery();
                while (result.next()) {
                    String activity = "Melakukan Penambahan data User";
                    ps = DB.getConnection().prepareStatement("CALL createLog('" + result.getString("kd_user") + "','" + activity + "');");
                    ps.executeUpdate();
                    break;
                }
            }
            statement.executeUpdate(sql);
            pop_upDataberhasil dataubah = new pop_upDataberhasil();
            dataubah.setVisible(true);
            statement.close();
            user.datatable();
            
            this.dispose();
            
        } catch (Exception e) {
            System.out.println(e);
            pop_upDataGagal datagagal = new pop_upDataGagal();
            datagagal.setVisible(true);
        }
    }//GEN-LAST:event_saveMouseClicked
