    void getData(String id_user) {
        
        try {
            
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery("SELECT * FROM user where kd_user ='" + id_user + "'");
            String role = "";
            while (res.next()) {
                namaLengkap.setText(res.getString("nama_lengkap"));
                username.setText(res.getString("username"));
                jPasswordField.setText(res.getString("password"));
                Alamat.setText(res.getString("alamat"));
                noHp.setText(res.getString("hp"));
                role = res.getString("role");
                RFID = res.getString("rfid");
            }
            System.out.println(role);
            if (role.equals("Admin")) {
                jadmin.getModel().setSelected(true);
            } else {
                jowner.getModel().setSelected(true);
            }
        } catch (Exception e) {
            pop_upnoData nodata = new pop_upnoData();
            nodata.setVisible(true);
        }
    }
