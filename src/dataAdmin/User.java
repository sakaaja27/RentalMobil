    public void datatable() {
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kode User");
        tbl.addColumn("Kode User");
        tbl.addColumn("Nama Lengkap");
        tbl.addColumn("Username");
        tbl.addColumn("Role");
        jTableUser.setModel(tbl);
        jTableUser.getColumnModel().getColumn(0).setMinWidth(0);
        jTableUser.getColumnModel().getColumn(0).setMaxWidth(0);

        String cari = jTextField_search.getText();

        ArrayList<String> filter = new ArrayList();
        StringBuilder sql = new StringBuilder("SELECT * FROM user");
        if (!cari.isEmpty()) {
            filter.add("kd_user  LIKE '%" + cari + "%' OR nama_lengkap LIKE '%" + cari + "%'");
        }
        
        if (!filter.isEmpty()) {
            sql.append(" WHERE ").append(String.join(" AND ", filter));
        }
        String newSql = sql.toString();
        System.out.println(newSql);
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_user"),
                    res.getString("kd_user"),
                    res.getString("nama_lengkap"),
                    res.getString("username"),
                    res.getString("role")
                });
                jTableUser.setModel(tbl);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data tidak ada");
        }
    }
