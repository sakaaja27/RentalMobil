    private void jButton_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_hapusActionPerformed
        // TODO add your handling code here:
        try {
            if (id != null) {
                Statement statement = (Statement) DB.getConnection().createStatement();
                String sql;
                sql = "DELETE FROM mobil where id_mobil = '"+kodeMobil.getText()+"'";
                java.sql.Connection conn = (Connection) DB.getConnection();
                java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                pst.execute();
                JOptionPane.showMessageDialog(this,"Data berhasil dihapus"); 
                this.dispose();
            } else {
                namaMobil.setText(null);
                nopolMobil.setText(null);
                jComboBox_pemilik.setSelectedItem(this);
                tahun.setText(null);
                harga.setText(null);
                JOptionPane.showMessageDialog(this,"Data berhasil dikosongkan"); 
                
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_jButton_hapusActionPerformed

    public ImageIcon resizeImage(String imagePath){
        ImageIcon imgIcon = new ImageIcon(imagePath);
        Image img = imgIcon.getImage();
        Image newImg = img.getScaledInstance(jLabel_foto.getWidth(), jLabel_foto.getHeight(), Image.SCALE_SMOOTH);
        ImageIcon image = new ImageIcon(newImg);
        return image;
    }
    void getPemilik(){
        nm_pemilik = new ArrayList<String>();
        kd_pemilik = new ArrayList<String>();
        try{
            Statement state = DB.getConnection().createStatement();
            ResultSet res = state.executeQuery("select id_pemilik, nama_pemilik from pemilik_mobil");
            while(res.next()){
                jComboBox_pemilik.addItem(res.getString("nama_pemilik"));
                kd_pemilik.add(res.getString("id_pemilik"));
            }

        }catch(Exception x){
            JOptionPane.showMessageDialog(rootPane, x);
        
        }   
    }
