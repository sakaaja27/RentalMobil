    void getData(String id_mobil) {
        try {
          
             Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery("SELECT pemilik_mobil.nama_pemilik,mobil.* FROM mobil inner join pemilik_mobil ON pemilik_mobil.id_pemilik = mobil.id_pemilik where id_mobil ='"+id_mobil+"'");
            
            while (res.next()) {
               namaMobil.setText(res.getString("nama_mobil"));
                    nopolMobil.setText(res.getString("nopol"));
                    jComboBox_pemilik.setSelectedItem(res.getString("nama_pemilik"));
                    tahun.setText(res.getString("tahun_produksi"));
                   harga.setText(res.getString("harga_perhari"));
//                     res.getString("gambar"),
//                    status.setText(res.getString("nopol"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Data tidak ada");
        }
    }

