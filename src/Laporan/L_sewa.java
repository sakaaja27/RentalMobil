    void datatable(String d1,String d2){
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kd detail sewa");
        tbl.addColumn("Nama Customer");
        tbl.addColumn("Nama User");
        tbl.addColumn("Nama Mobil");
        tbl.addColumn("Nama Supir");
        tbl.addColumn("Tgl Sewa");
        tbl.addColumn("Jumlah Hari");
        tbl.addColumn("Subtotal");
        Laporan_sewa.setModel(tbl);
        
         PreparedStatement st;
        ResultSet res;
        try {
            if (d1.equals("") || d2.equals("")) {
                st = DB.getConnection().prepareStatement("SELECT kd_detail_sewa,nama_customer,nama_user,nama_mobil,nama_supir,tgl_sewa,jml_hari,subtotal FROM `v_detailsewa`;");
            }
            else {
                st = DB.getConnection().prepareStatement("SELECT kd_detail_sewa,nama_customer,nama_user,nama_mobil,nama_supir,tgl_sewa,jml_hari,subtotal FROM `v_detailsewa` where tgl_sewa between ? and ? ");
                st.setString(1, d1);
                st.setString(2, d2);
            }
            
            res = st.executeQuery();
            DefaultTableModel model = (DefaultTableModel) Laporan_sewa.getModel();
            
            Object[] row;
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_detail_sewa"),
                    res.getString("nama_customer"),
                    res.getString("nama_user"),
                    res.getString("nama_mobil"),
                    res.getString("nama_supir"),
                    res.getString("tgl_sewa"),
                    res.getString("jml_hari"),
                    res.getString("subtotal")
                });
                Laporan_sewa.setModel(tbl);
            }
        }
        catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data tidak ada");
        }
    }
        
        
