    void datatable(String d1, String d2) {
        DefaultTableModel tbl = new DefaultTableModel();

        tbl.addColumn("Tanggal");
        tbl.addColumn("Uang");

        Laporan_sewa.setModel(tbl);

        PreparedStatement st;
        ResultSet res;
        try {
            if (d1.equals("") || d2.equals("")) {
                st = DB.getConnection().prepareStatement("SELECT Date,subtotal FROM `v_laporan`");
            } else {
                st = DB.getConnection().prepareStatement("SELECT Date,subtotal FROM `v_laporan` where Date between ? and ? ");
                st.setString(1, d1);
                st.setString(2, d2);
            }

            res = st.executeQuery();
            DefaultTableModel model = (DefaultTableModel) Laporan_sewa.getModel();

            Object[] row;
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("Date"),
                    res.getString("subtotal")
                });
                Laporan_sewa.setModel(tbl);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data tidak ada");
        }

    }

    public void generateChart() {
        try {
            List<ModelData> lists = new ArrayList<>();
            DB.getConnection().createStatement();
            String sql = "select DATE_FORMAT(MAX(l.Date),'%M') as `Month`, SUM(l.subtotal) as Amount from v_laporan l group by DATE_FORMAT(l.Date,'%m%Y') order by MAX(l.Date) DESC limit 7";
            PreparedStatement p = DB.getConnection().prepareStatement(sql);
            ResultSet r = p.executeQuery();
            while (r.next()) {
                String month = r.getString("Month");
                double amount = r.getDouble("Amount");

                lists.add(new ModelData(month, amount));
            }
            r.close();
            p.close();
            //  Add Data to chart
            String[] shortMonths = {"Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"};

            String[] months = {"January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"};
            String[] amountPerMonth = new String[months.length];
            for (int i = 0; i < months.length; i++) {
//                monthsWithValue[i][0] = months[i];
                for (int j = 0; j < lists.size(); j++) {
                    if (months[i].equals(lists.get(j).getMonth())) {
                        amountPerMonth[i] = String.valueOf(lists.get(j).getAmount());
                        break;
                    } else {
                        amountPerMonth[i] = "0";
                    }
                }
            }
            for (int i = 0; i < amountPerMonth.length; i++) {
                System.out.println(shortMonths[i] + " " + amountPerMonth[i]);
                chart.addData(new ModelChart(shortMonths[i], new double[]{Double.parseDouble(amountPerMonth[i])}));
            }
//            for (int i = lists.size() - 12; i >= 0; i--) {
//                ModelData d = lists.get(i);
//            }
            //  Start to show data with animation
            chart.start();
        } catch (Exception e) {
            System.out.println(e);
        }

    }
