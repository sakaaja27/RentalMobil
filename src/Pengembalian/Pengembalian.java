    public void datatable(){
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kode Penyewaan");
       tbl.addColumn("Nama Customer");
       tbl.addColumn("Nama Admin");
       tbl.addColumn("Total Harga");
       tbl.addColumn("Tanggal Pesanan");
       jTable_pengembalian.setModel(tbl);
       
       String cari = jTextField_search.getText();
        String filterStatus = jComboBox_filterStatus.getSelectedItem().toString();
        ArrayList<String> filter = new ArrayList<>();
        StringBuilder sql = new StringBuilder("SELECT penyewaan.*,user.nama_lengkap AS nm_admin,customer.nama_lengkap AS nm_cust,customer.no_ktp FROM penyewaan INNER JOIN customer on customer.kd_customer = penyewaan.kd_customer INNER JOIN user ON user.kd_user = penyewaan.kd_user");
        if (!cari.isEmpty()) {
            filter.add("penyewaan.kd_penyewaan LIKE '%" + cari + "%'");
        }
//        if (!filterStatus.isEmpty()) {
//            filter.add("status = '" + filterStatus + "'");
//        }
        if (!filter.isEmpty()) {
            sql.append(" WHERE ").append(String.join(" AND ", filter));
        }
        String newSql = sql.toString();
        System.out.println(newSql);
        try {

            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_penyewaan"),
                    res.getString("nm_admin"),
                    res.getString("nm_cust"),
                    res.getString("total_harga"),
                    res.getString("tgl_pesan")
                });
                jTable_pengembalian.setModel(tbl);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,e.getMessage());
        }
       
       
    }

