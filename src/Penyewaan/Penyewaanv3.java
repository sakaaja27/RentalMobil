    public void generateTablePenyewaanMaster() {
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kode Transaksi");
        tbl.addColumn("Nama Customer");
        tbl.addColumn("Total Harga");
        tbl.addColumn("Tgl. Transaksi");
        jTable_penyewaanMaster.setModel(tbl);
        String cari = jTextField_search1.getText();
       
        StringBuilder sql = new StringBuilder("SELECT * FROM v_data_penyewaan WHERE kd_penyewaan LIKE '%" + cari + "%'");
        String newSql = sql.toString();
//        System.out.println(newSql);
        try {

            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {

                tbl.addRow(new Object[]{
                    res.getString("kd_penyewaan"),
                    res.getString("nama_customer"),
                    res.getString("total_harga"),
                    res.getString("tgl_transaksi")
                });
            }
            jTable_penyewaanMaster.setModel(tbl);
        } catch (Exception e) {
            pop_upnoData nodata = new pop_upnoData();
            nodata.setVisible(true);
        }

    }

    public void generateTablePenyewaanDetail(String kd_penyewaan) {
        DefaultTableModel tbl = new DefaultTableModel();
        tbl.addColumn("Kode Detail Sewa");
        tbl.addColumn("Nama Mobil");
        tbl.addColumn("Harga perhari");
        tbl.addColumn("Jumlah Hari");
        tbl.addColumn("Nama Supir");
        tbl.addColumn("Tgl. Sewa");
        tbl.addColumn("Tgl. Tenggat");
        tbl.addColumn("Sub total");
        tbl.addColumn("Status");
        
        jTable_penyewaanDetail.setModel(tbl);
        StringBuilder sql = new StringBuilder("SELECT * FROM v_detailsewa");
        String newSql = sql.toString().concat(" WHERE v_detailsewa.kd_penyewaan LIKE '%" + kd_penyewaan + "%'");
        try {
            Statement statement = (Statement) DB.getConnection().createStatement();
            ResultSet res = statement.executeQuery(newSql);
            while (res.next()) {
                tbl.addRow(new Object[]{
                    res.getString("kd_detail_sewa"),
                    res.getString("nama_mobil"),
                    res.getString("harga_perhari"),
                    res.getString("jml_hari"),
                    res.getString("nama_supir"),
                    res.getString("tgl_sewa"),
                    res.getString("tgl_tenggat"),
                    res.getString("subtotal"),
                    res.getString("status")
                  
                });
            }
            jTable_penyewaanDetail.setModel(tbl);
        } catch (Exception e) {
            pop_upnoData nodata = new pop_upnoData();
            nodata.setVisible(true);
        }

    }

